"""Emit the per-project artifacts: manifest, guard, hooks, thin AGENTS.md, CLAUDE.md, COVERAGE.

This file no longer knows what a Claude Code settings file looks like. Each host lives in
init/targets/ and hands back `{path, content, note}` items; the generator's job is the part
that is the same for all of them -- classify every destination before a byte lands, write all
of it or none of it, and preserve the human's tail. `merge_settings` moved to
targets/claude.py, where Claude Code's config schema belongs, and is re-exported here so
existing callers keep working.

Design rules that came straight out of the plan reviews:
  - AGENTS.md stays THIN (EXTENDING.md Rule 2): it names the pillars that apply and the one
    hard rule, and defers all depth to the skills. It never inlines skill content.
  - .claude/settings.json is MERGED, not overwritten: an existing hook set is preserved and
    the mir hook is reconciled to the desired shape, so re-running is idempotent.
  - Every generated file carries an ownership marker so a human and a re-run both know mir
    owns it. Content below the marker is preserved on regeneration, in EVERY artifact that
    offers a tail -- the marker is an address, not a flag.
  - Nothing is written to a destination that has not been inspected first. Every write
    target is classified (absent / mir-owned / unowned / symlink / non-regular /
    unparseable) BEFORE the first byte lands, and a destination mir does not own aborts the
    whole run. A partial harness is worse than none, because it looks installed.
  - --dry-run prints the diff of what would change and writes nothing -- including no
    backups, which is why refusal is decided in plan() and executed in apply().
"""

